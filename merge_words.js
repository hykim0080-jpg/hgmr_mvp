function run() {
  console.log("=== 1단계: 1차 50개 단어 추가 ===");
  if (!fs.existsSync(wordsFilePath)) {
    console.error("Error: words.json 파일이 존재하지 않습니다.");
    process.exit(1);
  }

  const fileContent = fs.readFileSync(wordsFilePath, 'utf8');
  let originalWords = JSON.parse(fileContent);
  const initialCount = originalWords.length;
  console.log(`기존 단어 수: ${initialCount}개`);

  // 중복 검사 및 1차 추가
  const currentTargets = new Set(originalWords.map(w => w.target));
  const addedBatch1 = [];
  
  for (const word of batch1) {
    if (!currentTargets.has(word.target)) {
      originalWords.push(word);
      currentTargets.add(word.target);
      addedBatch1.push(word.target);
    } else {
      console.warn(`[Batch 1 경고] 중복 단어 발견으로 건너뜀: ${word.target}`);
    }
  }
  
  console.log(`1차 단어 추가 완료: ${addedBatch1.length}개 추가됨.`);
  console.log(`1차 병합 후 단어 수: ${originalWords.length}개`);

  console.log("\n=== 2단계: 2차 50개 단어 추가 ===");
  const addedBatch2 = [];
  
  for (const word of batch2) {
    if (!currentTargets.has(word.target)) {
      originalWords.push(word);
      currentTargets.add(word.target);
      addedBatch2.push(word.target);
    } else {
      console.warn(`[Batch 2 경고] 중복 단어 발견으로 건너뜀: ${word.target}`);
    }
  }

  console.log(`2차 단어 추가 완료: ${addedBatch2.length}개 추가됨.`);
  console.log(`최종 병합 후 단어 수: ${originalWords.length}개`);

  // 3단계: 정합성 검증 및 가나다라 정렬
  console.log("\n=== 3단계: 정합성 검증 및 가나다라 정렬 ===");
  const expectedTotal = initialCount + addedBatch1.length + addedBatch2.length;
  if (originalWords.length !== expectedTotal) {
    console.error(`정합성 오류: 기대 단어 수 ${expectedTotal}개이나, 실제 ${originalWords.length}개입니다.`);
    process.exit(1);
  }
  console.log(`정합성 검증 성공: 최종 단어 수 ${originalWords.length}개가 기대 수 ${expectedTotal}개와 일치합니다.`);

  // 가나다라 정렬 (target 가나다순 정렬)
  originalWords.sort((a, b) => a.target.localeCompare(b.target, 'ko'));

  // 정렬 후 저장
  fs.writeFileSync(wordsFilePath, JSON.stringify(originalWords, null, 4), 'utf8');
  console.log("words.json 파일에 가나다라 정렬하여 안전하게 저장 완료!");
}

run();
